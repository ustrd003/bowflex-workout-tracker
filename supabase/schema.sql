  end if;
  if to_regclass('public.cardio_entries') is not null
     and to_regclass('public.w_cardio_entries') is null then
    alter table public.cardio_entries rename to w_cardio_entries;
  end if;
  if to_regclass('public.weekly_weights') is not null
     and to_regclass('public.w_weekly_weights') is null then
    alter table public.weekly_weights rename to w_weekly_weights;
  end if;
end
$$;

create table if not exists public.w_users (
  user_key text primary key,
  display_name text not null unique
);

insert into public.w_users (user_key, display_name)
